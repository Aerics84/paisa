package config

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sync"
	"time"

	"dario.cat/mergo"
	"gopkg.in/yaml.v3"
)

// ErrReadonly is returned by Store.Update when the loaded configuration is
// marked as read-only.
var ErrReadonly = errors.New("configuration is read-only")

// Store holds the active configuration behind a read/write lock. Published
// snapshots are never mutated in place: readers receive a deep clone and
// writers swap a freshly built snapshot atomically.
type Store struct {
	mu          sync.RWMutex
	config      Config
	configPath  string
	location    *time.Location
	initialized bool
	autoCreated bool
	onboarding  bool
	updateMu    sync.Mutex
}

// NewStore returns an empty, uninitialized store.
func NewStore() *Store {
	return &Store{}
}

// Clone returns a deep copy of the configuration. Callers may mutate the
// result without affecting the receiver.
func (c Config) Clone() Config {
	content, err := json.Marshal(c)
	if err != nil {
		panic(fmt.Sprintf("config.Clone: %v", err))
	}

	var clone Config
	if err := json.Unmarshal(content, &clone); err != nil {
		panic(fmt.Sprintf("config.Clone: %v", err))
	}

	return clone
}

// Load parses, validates and replaces the configuration. The previously
// published snapshot stays untouched when parsing or validation fails.
func (s *Store) Load(content []byte, path string) error {
	s.updateMu.Lock()
	defer s.updateMu.Unlock()

	return s.loadLocked(content, path)
}

// loadLocked implements Load. The caller must hold updateMu.
func (s *Store) loadLocked(content []byte, path string) error {
	cfg, location, err := parseConfig(content)
	if err != nil {
		return err
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	s.config = cfg
	s.location = location
	if path != "" {
		s.configPath = path
	}
	s.initialized = true

	return nil
}

// LoadFile reads the configuration file at path and loads it. The read and the
// swap happen under the same sequence lock so a concurrent Update or SaveConfig
// cannot be reverted by a stale read.
func (s *Store) LoadFile(path string) error {
	absPath, err := filepath.Abs(path)
	if err != nil {
		return err
	}

	s.updateMu.Lock()
	defer s.updateMu.Unlock()

	content, err := os.ReadFile(absPath)
	if err != nil {
		return fmt.Errorf("failed to read config file %s: %w", absPath, err)
	}

	return s.loadLocked(content, absPath)
}

// Get returns a deep clone of the current configuration.
func (s *Store) Get() Config {
	s.mu.RLock()
	defer s.mu.RUnlock()

	return s.config.Clone()
}

// Update applies mutate to a clone of the current configuration, validates
// the result, writes it to disk and swaps the snapshot atomically. On any
// error the previous snapshot is kept.
func (s *Store) Update(mutate func(*Config) error) error {
	s.updateMu.Lock()
	defer s.updateMu.Unlock()

	s.mu.RLock()
	current := s.config
	path := s.configPath
	s.mu.RUnlock()

	if current.Readonly {
		return ErrReadonly
	}

	if path == "" {
		return errors.New("configuration path is not set")
	}

	next := current.Clone()
	if err := mutate(&next); err != nil {
		return err
	}

	if err := validateConfig(next); err != nil {
		return err
	}

	location, err := loadLocation(next.TimeZone)
	if err != nil {
		return err
	}

	content, err := yaml.Marshal(next)
	if err != nil {
		return err
	}

	if err := os.WriteFile(path, content, 0644); err != nil {
		return err
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	s.config = next
	s.location = location

	return nil
}

// Path returns the absolute path of the loaded configuration file.
func (s *Store) Path() string {
	s.mu.RLock()
	defer s.mu.RUnlock()

	return s.configPath
}

// ConfigDir returns the directory containing the configuration file.
func (s *Store) ConfigDir() string {
	return filepath.Dir(s.Path())
}

// TimeZone returns the configured time zone, falling back to time.Local.
func (s *Store) TimeZone() *time.Location {
	s.mu.RLock()
	defer s.mu.RUnlock()

	if s.location != nil {
		return s.location
	}

	return time.Local
}

// MarkAutoCreated records that a minimal configuration was generated by this
// process and is still awaiting onboarding.
func (s *Store) MarkAutoCreated() {
	s.mu.Lock()
	defer s.mu.Unlock()

	s.autoCreated = true
	s.initialized = false
}

// AutoCreated reports whether the current configuration was generated by this
// process and has not been initialized by the user yet.
func (s *Store) AutoCreated() bool {
	s.mu.RLock()
	defer s.mu.RUnlock()

	return s.autoCreated
}

// Initialized reports whether a configuration has been loaded from disk.
func (s *Store) Initialized() bool {
	s.mu.RLock()
	defer s.mu.RUnlock()

	return s.initialized
}

// TryBeginOnboarding atomically claims the onboarding lock. It succeeds at
// most once while the configuration is auto-created and not yet initialized.
func (s *Store) TryBeginOnboarding() bool {
	s.mu.Lock()
	defer s.mu.Unlock()

	if !s.autoCreated || s.initialized || s.onboarding {
		return false
	}

	s.onboarding = true
	return true
}

// AbortOnboarding releases the onboarding lock after a failed attempt so the
// user can retry.
func (s *Store) AbortOnboarding() {
	s.mu.Lock()
	defer s.mu.Unlock()

	s.onboarding = false
}

// MarkInitialized marks onboarding as complete and retires auto-created state.
func (s *Store) MarkInitialized() {
	s.mu.Lock()
	defer s.mu.Unlock()

	s.initialized = true
	s.autoCreated = false
	s.onboarding = false
}

// saveContent validates content, installs it as the current snapshot and
// writes it to the bound path as one serialized operation.
func (s *Store) saveContent(content []byte) error {
	s.updateMu.Lock()
	defer s.updateMu.Unlock()

	if err := s.loadLocked(content, ""); err != nil {
		return err
	}

	return s.writeSnapshotLocked()
}

// writeSnapshotLocked writes the current snapshot to the configured path. The
// caller must hold updateMu.
func (s *Store) writeSnapshotLocked() error {
	s.mu.RLock()
	cfg := s.config
	path := s.configPath
	s.mu.RUnlock()

	if path == "" {
		return errors.New("configuration path is not set")
	}

	content, err := yaml.Marshal(cfg)
	if err != nil {
		return err
	}

	return os.WriteFile(path, content, 0644)
}

// parseConfig turns raw YAML into a validated, defaulted configuration.
func parseConfig(content []byte) (Config, *time.Location, error) {
	var configJson any
	if err := yaml.Unmarshal(content, &configJson); err != nil {
		return Config{}, nil, err
	}

	normalizeConfig(configJson)

	rawConfig := map[string]any{}
	if err := yaml.Unmarshal(content, &rawConfig); err != nil {
		return Config{}, nil, err
	}

	if err := schema.Validate(configJson); err != nil {
		return Config{}, nil, errors.New(fmt.Sprintf("Invalid configuration\n%#v", err))
	}

	cfg := Config{}
	if err := yaml.Unmarshal(content, &cfg); err != nil {
		return Config{}, nil, err
	}

	for i := range cfg.Commodities {
		cfg.Commodities[i].Price.Provider = normalizePriceProvider(cfg.Commodities[i].Price.Provider)
	}

	if err := mergo.Merge(&cfg, defaultConfig, mergo.WithOverrideEmptySlice); err != nil {
		return Config{}, nil, err
	}

	applyRegionalProfileDefaults(rawConfig, &cfg)

	location, err := loadLocation(cfg.TimeZone)
	if err != nil {
		return Config{}, nil, err
	}

	return cfg, location, nil
}

// validateConfig validates a fully built configuration by round-tripping it
// through JSON, which the schema compiler expects as a generic object.
func validateConfig(cfg Config) error {
	content, err := json.Marshal(cfg)
	if err != nil {
		return err
	}

	object := map[string]any{}
	if err := json.Unmarshal(content, &object); err != nil {
		return err
	}

	// Optional struct fields without a JSON omitempty tag serialize as null;
	// the schema treats a missing key as unset, not null.
	for key, value := range object {
		if value == nil {
			delete(object, key)
		}
	}

	if err := schema.Validate(object); err != nil {
		return errors.New(fmt.Sprintf("Invalid configuration\n%#v", err))
	}

	return nil
}

func loadLocation(timeZone string) (*time.Location, error) {
	if timeZone == "" {
		return time.Local, nil
	}

	location, err := time.LoadLocation(timeZone)
	if err != nil {
		return nil, errors.New(fmt.Sprintf("Invalid time zone: %s\n%#v", timeZone, err))
	}

	return location, nil
}
